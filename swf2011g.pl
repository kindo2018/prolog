	 domain_n( 2, D),
	 aso( D, X, Y, Z).

rso( N, A, B, C ):-
	 integer( N), N > 2,
	 N1 is N -1,
	 rso( N1, X, Y, Z),
	 G = sign( P1),
	 E = ( [P1|P] -> V),
	 findall( E, (member( P->V, X), G), A),
	 findall( E, (member( P->V, Y), G), B),
	 findall( E, (member( P->V, Z), G), C),
	 aso( _D, A, B, C).


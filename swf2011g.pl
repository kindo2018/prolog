% a recursive prover

wso( 1, [X, Y, Z] ):-
	 hr( 1, [X, Y, Z] ).

wso( N, [X, Y, Z] ):-
	 integer( N), N > 1,
	 N1 is N - 1,
	 wso( N1, [X1, Y1, Z1]),
	 wso( N1, [A1, B1, C1]),
	 hr_merge( (+):[X1, Y1, Z1], (-):[A1, B1, C1], [X, Y, Z]),
	 aso( _D, X, Y, Z).

wso( N, [X, Y, Z] ):-
	 integer( N), N > 2,
	 N1 is N - 1,
	 cr( N1, +, [X1, Y1, Z1]),
	 cr( N1, -, [A1, B1, C1]),
	 hr_merge( (+):[X1, Y1, Z1], (-):[A1, B1, C1], [X, Y, Z]),
	 aso( _D, X, Y, Z).


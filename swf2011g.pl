% sign-based representation of (pairwise) preference ordering

sign(+).
sign(-).

% profile (a tuple of individual preferences) and domain

% profile of n-sign

sp( []).
sp( ['+'|P]):- sp( P).
sp( ['-'|P]):- sp( P).

domain_n( 1, [[+],[-]]).
domain_n( N, D):-
	 integer( N), N >1,
	 N1 is N - 1,
	 domain_n( N1, D1),
	 domain_n_m( D1, D).
domain_n_m( [], []).
domain_n_m( [P1|D1], [[+|P1], [-|P1] |D]):-
	 domain_n_m( D1, D).

% aggregating profile (a tuple of individual preferences) into a social ordering 


% individual ordering at a profile

kth_io( K, [P1K, P2K, P3K], [P1, P2, P3]):-
	 nth1(K, P1, P1K),
	 nth1(K, P2, P2K),
	 nth1(K, P3, P3K).

% intransitivity of individual or social ordering

v_intrans_so( [P1 -> V1, P2 -> V2, P3 -> V3]):- 
	 intrans_so( [P1 -> V1, P2 -> V2, P3 -> V3]),
	 !,
	 assert( step_vh( [ violate : transitivity, [P1 -> V1, P2 -> V2, P3 -> V3]])).

intrans_so( [P1 -> V1, P2 -> V2, P3 -> V3]):- 
	 intransitive( V1, V2, V3),
	 \+ (
		 kth_io( _, [A, B, C], [P1, P2, P3]),
		 intransitive( A, B, C)
	 ).

intransitive( A, A, A).

% social ordering at some profile

so_at( [P1 -> V1, P2 -> V2, P3 -> V3], X, Y, Z):-
	 member( P1 -> V1, X),
	 member( P2 -> V2, Y),
	 member( P3 -> V3, Z).


% Arrow social welfare function

% transitive and universal social ordering 
% that satisfies both independence and weak pareto (unanimity) 

% verbalized aso

vaso( [], [], [], []).
vaso( [P|D], [P->V1|X], [P->V2|Y], [P->V3|Z]):-
	 vaso( D, X, Y, Z),
 	 sp( [V1, V2, V3]),
	 assert(
		 step_vh( [ try : [X, Y, Z], P, [V1, V2, V3] ])
	 ),
	 vuso( P, V1, V2, V3),  
	 assert(
		 step_vh( [ ok(u) : [X, Y, Z], P, [V1, V2, V3] ])
	 ),
	 \+ v_violate_trans_so( [P->V1|X], [P->V2|Y], [P->V3|Z]),
	 assert(
		 step_vh( [ ok(t) : [X, Y, Z], P, [V1, V2, V3] ])
	 ).

aso( [], [], [], []).
aso( [P|D], [P->V1|X], [P->V2|Y], [P->V3|Z]):-
	 aso( D, X, Y, Z),
 	 sp( [V1, V2, V3]),
	 uso( P, V1, V2, V3),  
	 \+ violate_trans_so( [P->V1|X], [P->V2|Y], [P->V3|Z]).

% proof steps verbalized

vuso( P, V1, V2, V3):-
	 uso( P, V1, V2, V3),
	 !.
vuso( P, V1, V2, V3):-
	 assert( step_vh( [ violate: unanimity, P, [V1, V2, V3]])),
	 fail. 

% detect intransitivity 

v_violate_trans_so( [P->V1|X], [P->V2|Y], [P->V3|Z]):-
	 so_at( PV, [P->V1|X], [P->V2|Y], [P->V3|Z]), 
	 v_intrans_so( PV).

violate_trans_so( [P->V1|X], [P->V2|Y], [P->V3|Z]):-
	 so_at( PV, [P->V1|X], [P->V2|Y], [P->V3|Z]), 
	intrans_so( PV).

% unanimity

uso( P, V, V, V):-
	 sort( P, [V]).
uso( P, _, _, _):-
	 \+ sort( P, [_]).

% independence only

iso( [], [], [], []).
iso( [P|D], [P->V1|X], [P->V2|Y], [P->V3|Z]):-
	 iso( D, X, Y, Z),
 	 sp( [V1, V2, V3]),
%	 uso( P, V1, V2, V3),  
	 \+ (
		 so_at( PV, [P->V1|X], [P->V2|Y], [P->V3|Z]), 
		 intrans_so( PV)
	 ).


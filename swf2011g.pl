% breifing a proof



pbrf:-
	 pbrf( P),
	 member( X, P),
	 nl,
	 write( X),
	 fail.
pbrf:-
	 nl, 
	 write(qed).

pbrf( P):-
	 findall( A, (
		 step_vh( A),
		 A = [ ok( t):_ | _]
	 ),  P).


pbrf1( P):-
	 findall( A, step_vh( A), L),
	 pbrf( L, _, P).

% the bif. patterns of step_vh data
% try -> violate ; ok(u) -> violate ; ok(t) -> violate 

pbrf( [], start, []).
pbrf( [P | L], try, [A | H]):-
	 P = [try | A],
	 pbrf( L, _, H).  % skip if continuation of seeking a sol
pbrf(  [P | L], violate( A), H):-
	 P = [violate: A | _],
	 pbrf( L, _, [ _ | H]).  % skip and remove a trial if fail 
pbrf( [ P | L], ok( A), H):-
	 P = [ ok( A) | _],
	 pbrf( L, _, H).  % skip and remove a trial if fail 

